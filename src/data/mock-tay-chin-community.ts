export interface TayChinHouseholdLocation {
  clusterId: string;
  roadName: string;
  coordinates: [number, number];
  osmBuildingId: number;
}

export interface TayChinCommunityPlace {
  id: string;
  layerId: string;
  name: string;
  coordinates: [number, number];
  roadName: string;
  description: string;
  facilityType: string;
  operatingStatus: string;
  scale: string;
  source: string;
}

function householdLocations(
  clusterId: string,
  roadName: string,
  locations: Array<[number, number, number]>,
): TayChinHouseholdLocation[] {
  return locations.map(([longitude, latitude, osmBuildingId]) => ({
    clusterId,
    roadName,
    coordinates: [longitude, latitude],
    osmBuildingId,
  }));
}

