/**
 * Helper: look up village metadata by code for property enrichment.
 * We join geometry with master data rather than duplicating fields.
 */
function villageProps(code: string) {
  const v = VILLAGES.find((v) => v.code === code);
  return {
    villageCode: v?.code ?? code,
    villageName: v?.name ?? code,
    areaHa: v?.areaHa ?? 0,
    population: v?.population ?? 0,
    householdCount: v?.householdCount ?? 0,
    dataStatus: 'mock',
    sourceCrs: 'VN-2000',
    displayCrs: 'EPSG:4326',
    disclaimer:
      'Dữ liệu ranh giới thôn là mô phỏng, không có giá trị pháp lý chính thức.',
  };
}

